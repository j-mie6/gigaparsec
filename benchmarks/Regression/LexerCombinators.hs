-------------------------------------------------------------------------------
-- DList

newtype DList a = DList ([a] -> [a])
  deriving(Generic, Semigroup, Monoid)
  
type DString = DList Char

instance IsString (DList Char) where
  fromString :: String -> DList Char
  fromString = fromList

instance IsString a => IsString (Gen a) where
  fromString = pure . fromString

dEmpty :: DList a
dEmpty = DList id

singleton :: a -> DList a
singleton x = DList (x :)

cons :: a -> DList a -> DList a
cons x (DList xs) = DList ((x :) . xs)

consM :: Applicative f => f a -> f (DList a) -> f (DList a)
consM x xs = cons <$> x <*> xs

append :: DList a -> DList a -> DList a
append (DList xs) (DList ys) = DList (xs . ys)

fromList :: [a] -> DList a
fromList xs = DList (xs ++)

toList :: DList a -> [a]
toList (DList xs) = xs []


instance Semigroup a => Semigroup (Gen a) where
  (<>) :: Gen a -> Gen a -> Gen a
  xs <> ys = (<>) <$> xs <*> ys

instance Monoid a => Monoid (Gen a) where
  mempty :: Gen a
  mempty = pure mempty

-------------------------------------------------------------------------------
-- Generating combinators

identStartList :: [Char]
identStartList = ['a' .. 'z'] ++ ['A' .. 'Z']
identLetterList :: [Char]
identLetterList = ['0' .. '9'] ++ identStartList

spacesList :: [Char]
spacesList = [' ', '\n']

genSpace :: Gen Char
genSpace = frequency [(10, pure ' '), (1, pure '\n')]

genIdent :: Gen DString
genIdent = 
      cons 
  <$> elements identStartList 
  <*> (fromList <$> (listOf (elements identLetterList)))

genSpaces :: Gen DString
genSpaces = fromList <$> listOf genSpace

genSpaces1 :: Gen DString
genSpaces1 = fromList <$> listOf1 genSpace

genEscapeChar :: Gen DString
genEscapeChar = cons '\\' . fromList <$> elements escapeLiteralsAll

genStringChar :: Gen DString
genStringChar = singleton <$> (
    chooseEnum ('\27', maxBound) `suchThat` (\c -> 
      (isAscii c) && c /= '"' && c /= '\\' && not (isControl c))
  )

genString :: Gen DString
genString = 
     "\"" 
  <> (mconcat <$> listOf (frequency [(8, genStringChar), (1, genEscapeChar)]))
  <> "\""

-------------------------------------------------------------------------------
-- Benchmark Generators

genIdentAndSpaces :: Int -> Gen String
genIdentAndSpaces size = 
  toList <$> go size (pure dEmpty)
  where 
    go :: Int -> Gen DString -> Gen DString
    go 0 xs = xs
    go n xs = go (n - 1) (xs <> genIdent <> genSpaces1)

genIdentStringSpaces :: Int -> Gen String
genIdentStringSpaces size = 
  toList <$> go size (pure dEmpty)
  where 
    go :: Int -> Gen DString -> Gen DString
    go 0 xs = xs
    go n xs = go (n - 1) (xs <> (oneof [genIdent, genString]) <> genSpaces1)

-------------------------------------------------------------------------------
-- Benchmark

lexerCombinators :: Benchmark
lexerCombinators = 
  let runIdentSpaces :: String -> (String -> Maybe [String]) -> Benchmark
      runIdentSpaces = benchmarkStrings [
          ("idents_spaces:10", generate (genIdentAndSpaces 10))
        , ("idents_spaces:100", generate (genIdentAndSpaces 100))
        , ("idents_spaces:1000", generate (genIdentAndSpaces 1000))
        ]
      runIdentStringSpaces :: String -> (String -> Maybe [String]) -> Benchmark
      runIdentStringSpaces = benchmarkStrings [
          ("idents_strings_spaces:10", generate (genIdentStringSpaces 10))
        , ("idents_strings_spaces:100", generate (genIdentStringSpaces 100))
        , ("idents_strings_spaces:1000", generate (genIdentStringSpaces 1000))
        ]
  in bgroup "LexerCombinators" [
      bgroup "IdentSpaces" [
        runIdentSpaces "Hand-Rolled" (gigaParse Hand.manyIdents)
      , runIdentSpaces "Token.Lexer.Patterns" (gigaParse Patt.manyIdents)
      ,  runIdentSpaces "Token.Lexer" (gigaParse Gend.manyIdents)
      ] 
    , bgroup "IdentStringSpaces" [
        runIdentStringSpaces "Hand-Rolled" (gigaParse Hand.manyIdents)
      , runIdentStringSpaces "Token.Lexer.Patterns" (gigaParse Patt.manyIdents)
      ,  runIdentStringSpaces "Token.Lexer" (gigaParse Gend.manyIdents)
      ]
    ]
