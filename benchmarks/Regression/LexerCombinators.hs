newtype DList a = DList ([a] -> [a])
type DString = DList Char

dEmpty :: DList a
dEmpty = DList id

singleton :: a -> DList a
singleton x = DList (x :)

cons :: a -> DList a -> DList a
cons x (DList xs) = DList ((x :) . xs)

append :: DList a -> DList a -> DList a
append (DList xs) (DList ys) = DList (xs . ys)

fromList :: [a] -> DList a
fromList xs = DList (xs ++)

toList :: DList a -> [a]
toList (DList xs) = xs []

identStartList :: [Char]
identStartList = ['a' .. 'z'] ++ ['A' .. 'Z']
identLetterList :: [Char]
identLetterList = ['0' .. '9'] ++ identStartList


spacesList :: [Char]
spacesList = [' ', '\n']

genIdent :: Gen DString
genIdent = 
  let ident = (elements identStartList)
  in cons <$> ident <*> (fromList <$> (listOf (elements identLetterList)))

genSpaces :: Gen DString
genSpaces = fromList <$> listOf (elements spacesList)

genSpaces1 :: Gen DString
genSpaces1 = fromList <$> listOf1 (elements spacesList)


genIdentAndSpaces :: Int -> Gen String
genIdentAndSpaces size = 
  let dstr = go size (pure dEmpty)
  in  toList <$> dstr
  where 
    go :: Int -> Gen DString -> Gen DString
    go 0 xs = xs
    go n xs = 
      let foo = append <$> genIdent <*> genSpaces
      in  go (n - 1) (append <$> xs <*> foo)

lexerCombinators :: Benchmark
lexerCombinators = 
  let runTest :: String -> (String -> Maybe [String]) -> Benchmark
      runTest = benchmarkStrings [
          ("idents_and_spaces:200", generate (genIdentAndSpaces 200))
        , ("idents_and_spaces:1000", generate (genIdentAndSpaces 1000))
        , ("idents_and_spaces:10000", generate (genIdentAndSpaces 10000))
        ]
  in bgroup "LexerCombinators" [
      runTest "Hand-Rolled" (gigaParse Hand.manyIdents)
    , runTest "Token.Lexer" (gigaParse Gend.manyIdents)
    , runTest "Token.Lexer.Patterns" (gigaParse Patt.manyIdents)
    ] 
